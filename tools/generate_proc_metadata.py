"""Generate command dispatch scopes and extension owners from the pinned registry."""
import argparse
from pathlib import Path
import xml.etree.ElementTree as ET

ROOT = Path(__file__).resolve().parents[1]
OUTPUT = ROOT / "layer/src/main/cpp/core/proc_metadata.inc"


def vulkan(element):
    return element.get("api") is None or "vulkan" in element.get("api").split(",")


def generate():
    registry = ET.parse(ROOT / "Vulkan-Headers/registry/vk.xml").getroot()
    commands = {c.get("name") or c.findtext("proto/name"): c
                for c in registry.findall("./commands/command") if vulkan(c)}
    owners = {}
    for feature in registry.findall("feature"):
        if not vulkan(feature):
            continue
        for req in feature.findall("require"):
            if vulkan(req):
                for ref in req.findall("command"):
                    if vulkan(ref):
                        owners.setdefault(ref.get("name"), [False, set(), set()])[0] = True
    for extension in registry.findall("./extensions/extension"):
        if "vulkan" not in extension.get("supported", "").split(","):
            continue
        index = 1 if extension.get("type") == "instance" else 2
        for req in extension.findall("require"):
            if vulkan(req):
                for ref in req.findall("command"):
                    if vulkan(ref):
                        owners.setdefault(ref.get("name"), [False, set(), set()])[index].add(extension.get("name"))
    lines = ["// Generated by tools/generate_proc_metadata.py; do not edit."]
    for name, (core, instance, device) in sorted(owners.items()):
        command = commands[name]
        while command.get("alias"):
            command = commands[command.get("alias")]
        first = next(p for p in command.findall("param") if vulkan(p)).findtext("type")
        scope = {"VkInstance": "Instance", "VkPhysicalDevice": "Physical",
                 "VkDevice": "Device", "VkQueue": "Device", "VkCommandBuffer": "Device"}.get(first, "Global")
        lines.append(f'{{"{name}", ProcScope::{scope}, {str(core).lower()}, '
                     f'"{"|".join(sorted(instance))}", "{"|".join(sorted(device))}"}},')
    return "\n".join(lines) + "\n"


if __name__ == "__main__":
    parser = argparse.ArgumentParser()
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    content = generate()
    if args.check:
        if not OUTPUT.exists() or OUTPUT.read_text(encoding="utf-8") != content:
            raise SystemExit("proc_metadata.inc is stale")
    else:
        OUTPUT.write_text(content, encoding="utf-8", newline="\n")
    print(f"{len(content.splitlines()) - 1} command scopes/owners {'verified' if args.check else 'generated'}")
