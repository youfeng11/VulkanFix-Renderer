"""Compile the tiny POST fixtures offline; no shader compiler ships in the APK."""
import argparse
import hashlib
from pathlib import Path
import struct
import subprocess
import tempfile

ROOT = Path(__file__).resolve().parents[1]
DIRECTORY = ROOT / "layer/src/main/cpp/diagnostics"


def generate(glslc, validator):
    lines = ["// Generated by tools/generate_driver_post_shaders.py using NDK r27d.", "#pragma once"]
    with tempfile.TemporaryDirectory(prefix="vulkanfix-post-shaders-") as temporary:
        for name in ("push.comp", "draw.vert", "draw.frag", "parameters.vert", "stores.vert", "sampler.frag"):
            source = DIRECTORY / "shaders" / name
            output = Path(temporary) / "shader.spv"
            target = "vulkan1.0"
            subprocess.run([glslc, f"--target-env={target}", "-O", str(source), "-o", str(output)], check=True)
            subprocess.run([validator, "--target-env", target, str(output)], check=True)
            data = output.read_bytes()
            words = struct.unpack(f"<{len(data) // 4}I", data)
            digest = hashlib.sha256(source.read_text(encoding="utf-8").encode("utf-8")).hexdigest()
            lines.append(f"// {name} SHA256 {digest}")
            lines.append(f"static constexpr uint32_t post_{name.replace('.', '_')}[] = {{")
            for i in range(0, len(words), 8):
                lines.append("    " + ", ".join(f"0x{w:08x}" for w in words[i:i+8]) + ",")
            lines.append("};")
    return "\n".join(lines) + "\n"


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--glslc", required=True)
    parser.add_argument("--spirv-val", required=True)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    generated = generate(args.glslc, args.spirv_val)
    header = DIRECTORY / "driver_post_shaders.h"
    if args.check:
        if not header.exists() or header.read_text(encoding="utf-8") != generated:
            parser.exit(1, "POST shader fixtures are stale; regenerate using NDK r27d.\n")
    else:
        header.write_text(generated, encoding="utf-8", newline="\n")
