"""Generate typed extension dependency expressions from the pinned Vulkan registry."""
import argparse
from pathlib import Path
import re
import xml.etree.ElementTree as ET


def generate(root):
    registry = ET.parse(root / 'Vulkan-Headers/registry/vk.xml').getroot()
    extensions = sorted((e for e in registry.findall('extensions/extension')
                         if 'vulkan' in e.get('supported', '').split(',')),
                        key=lambda e: e.get('name'))
    indices = {e.get('name'): i for i, e in enumerate(extensions)}
    nodes = []
    interned = {}

    def node(kind, a, b=0):
        value = (kind, a, b)
        if value not in interned:
            interned[value] = len(nodes)
            nodes.append(value)
        return interned[value]

    def version(name):
        match = re.fullmatch(r'VK_VERSION_(\d+)_(\d+)', name)
        if not match:
            raise ValueError(f'Not a core version: {name}')
        major, minor = map(int, match.groups())
        return (major << 22) | (minor << 12)

    def parse(expression):
        if not expression:
            return -1
        tokens = re.findall(r'[A-Za-z0-9_]+|[()+,]', expression)
        if ''.join(tokens) != expression:
            raise ValueError(f'Unsupported expression syntax: {expression}')
        position = 0

        def atom():
            nonlocal position
            token = tokens[position]
            position += 1
            if token == '(':
                result = either()
                if position >= len(tokens) or tokens[position] != ')':
                    raise ValueError(f'Unclosed expression: {expression}')
                position += 1
                return result
            if token in indices:
                return node('Extension', indices[token])
            return node('Version', version(token))

        def both():
            nonlocal position
            result = atom()
            while position < len(tokens) and tokens[position] == '+':
                position += 1
                result = node('And', result, atom())
            return result

        def either():
            nonlocal position
            result = both()
            while position < len(tokens) and tokens[position] == ',':
                position += 1
                result = node('Or', result, both())
            return result

        result = either()
        if position != len(tokens):
            raise ValueError(f'Trailing expression: {expression}')
        return result

    records = []
    for extension in extensions:
        promotion = extension.get('promotedto', '')
        promoted_version = version(promotion) if promotion.startswith('VK_VERSION_') else 0
        promoted_extension = indices[promotion] if promotion and not promoted_version else -1
        records.append((extension.get('name'), extension.get('type') == 'instance',
                        promoted_version, promoted_extension, parse(extension.get('depends', ''))))
    # Enabling an instance must never require a device extension.
    for name, instance, _, _, expression in records:
        def verify(index):
            if index < 0:
                return
            kind, a, b = nodes[index]
            if kind == 'Extension' and instance and not records[a][1]:
                raise ValueError(f'Instance dependency on a device extension: {name}')
            if kind in ('And', 'Or'):
                verify(a)
                verify(b)
        verify(expression)
    lines = ['// Generated by tools/generate_extension_dependencies.py; do not edit.',
             'constexpr DependencyNode dependency_nodes[] = {']
    lines += [f'    {{DependencyKind::{kind}, {a}, {b}}},' for kind, a, b in nodes]
    lines += ['};', 'constexpr ExtensionRecord extension_records[] = {']
    lines += [f'    {{"{name}", {str(instance).lower()}, {version}u, {promotion}, {expression}}},'
              for name, instance, version, promotion, expression in records]
    lines += ['};', '']
    return '\n'.join(lines), len(records), len(nodes)


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    root = Path(__file__).resolve().parents[1]
    output, records, nodes = generate(root)
    path = root / 'layer/src/main/cpp/core/extension_dependency_metadata.inc'
    if args.check:
        if not path.is_file() or path.read_text(encoding='utf-8') != output:
            raise SystemExit('Extension dependency metadata is stale')
    else:
        path.write_text(output, encoding='utf-8')
    print(f'Verified {records} extension records and {nodes} expression nodes')


if __name__ == '__main__':
    main()
