"""Generate promotion field maps and a complete 1.1/1.2 command/feature inventory.

The checked-in registry is the authority for layouts and the inventory. The
extension-to-core promotion list is deliberately explicit and reviewed here.
"""
from pathlib import Path
import json
import xml.etree.ElementTree as ET

ROOT = Path(__file__).resolve().parents[1]
REGISTRY = ROOT / "Vulkan-Headers/registry/vk.xml"
GROUPS = [
    (11, "VkPhysicalDevice16BitStorageFeatures", "VK_KHR_16bit_storage"),
    (11, "VkPhysicalDeviceMultiviewFeatures", "VK_KHR_multiview"),
    (11, "VkPhysicalDeviceVariablePointersFeatures", "VK_KHR_variable_pointers"),
    (11, "VkPhysicalDeviceProtectedMemoryFeatures", ""),
    (11, "VkPhysicalDeviceSamplerYcbcrConversionFeatures", "VK_KHR_sampler_ycbcr_conversion"),
    (11, "VkPhysicalDeviceShaderDrawParametersFeatures", "VK_KHR_shader_draw_parameters"),
    (12, "VkPhysicalDevice8BitStorageFeatures", "VK_KHR_8bit_storage"),
    (12, "VkPhysicalDeviceShaderAtomicInt64Features", "VK_KHR_shader_atomic_int64"),
    (12, "VkPhysicalDeviceShaderFloat16Int8Features", "VK_KHR_shader_float16_int8"),
    (12, "VkPhysicalDeviceDescriptorIndexingFeatures", "VK_EXT_descriptor_indexing"),
    (12, "VkPhysicalDeviceScalarBlockLayoutFeatures", "VK_EXT_scalar_block_layout"),
    (12, "VkPhysicalDeviceImagelessFramebufferFeatures", "VK_KHR_imageless_framebuffer"),
    (12, "VkPhysicalDeviceUniformBufferStandardLayoutFeatures", "VK_KHR_uniform_buffer_standard_layout"),
    (12, "VkPhysicalDeviceShaderSubgroupExtendedTypesFeatures", "VK_KHR_shader_subgroup_extended_types"),
    (12, "VkPhysicalDeviceSeparateDepthStencilLayoutsFeatures", "VK_KHR_separate_depth_stencil_layouts"),
    (12, "VkPhysicalDeviceHostQueryResetFeatures", "VK_EXT_host_query_reset"),
    (12, "VkPhysicalDeviceTimelineSemaphoreFeatures", "VK_KHR_timeline_semaphore"),
    (12, "VkPhysicalDeviceBufferDeviceAddressFeatures", "VK_KHR_buffer_device_address"),
    (12, "VkPhysicalDeviceVulkanMemoryModelFeatures", "VK_KHR_vulkan_memory_model"),
]
ALIASES = {
    "samplerMirrorClampToEdge": "VK_KHR_sampler_mirror_clamp_to_edge",
    "drawIndirectCount": "VK_KHR_draw_indirect_count",
    "descriptorIndexing": "VK_EXT_descriptor_indexing",
    "samplerFilterMinmax": "VK_EXT_sampler_filter_minmax",
    "shaderOutputViewportIndex": "VK_EXT_shader_viewport_index_layer",
    "shaderOutputLayer": "VK_EXT_shader_viewport_index_layer",
    "subgroupBroadcastDynamicId": "",
}


def generate():
    registry = ET.parse(REGISTRY).getroot()
    types = {t.get("name") or t.findtext("name"): t for t in registry.findall("./types/type")}
    types.pop(None, None)
    members = lambda t: [m.findtext("name") for m in types[t].findall("member")
                         if m.findtext("type") == "VkBool32"]
    lines = ["// Generated by tools/generate_core_feature_metadata.py; do not edit."]
    covered = {11: set(), 12: set(ALIASES)}
    for index, (version, name, extension) in enumerate(GROUPS):
        fields = members(name)
        covered[version].update(fields)
        lines.append(f"static const FeatureField fields_{index}[] = {{")
        lines.extend(f"    {{offsetof(VkPhysicalDeviceVulkan{version}Features, {f}), offsetof({name}, {f})}},"
                     for f in fields)
        lines.append("};")
    lines.append("static const FeatureGroup feature_groups[] = {")
    for index, (version, name, extension) in enumerate(GROUPS):
        stype = types[name].find("member[@values]").get("values")
        lines.append(f'    {{{version}, {stype}, sizeof({name}), "{extension}", '
                     f'VK_API_VERSION_1_{version - 10}, fields_{index}, std::size(fields_{index}), '
                     f'new_feature<{name}>, delete_feature<{name}>}},')
    lines.append("};")
    lines.append("static const FeatureAlias feature_aliases[] = {")
    for field, extension in ALIASES.items():
        lines.append(f'    {{offsetof(VkPhysicalDeviceVulkan12Features, {field}), "{extension}"}},')
    lines.append("};")
    for version in (11, 12):
        expected = set(members(f"VkPhysicalDeviceVulkan{version}Features"))
        assert expected == covered[version], (version, expected ^ covered[version])

    # Input pNext nodes must be copied before any module rewrites their links.
    # Include every current Vulkan device-create structure, guarded exactly as
    # the platform/provisional extension that declares it.
    platforms = {p.get("name"): p.get("protect") for p in registry.findall("./platforms/platform")}
    owners = {}
    for extension in registry.findall("./extensions/extension"):
        if "vulkan" not in extension.get("supported", "").split(","):
            continue
        protect = platforms.get(extension.get("platform"))
        if extension.get("provisional") == "true":
            protect = "VK_ENABLE_BETA_EXTENSIONS"
        for requirement in extension.findall("require"):
            if requirement.get("api") and "vulkan" not in requirement.get("api").split(","):
                continue
            for t in requirement.findall("type"):
                if not t.get("api") or "vulkan" in t.get("api").split(","):
                    owners.setdefault(t.get("name"), set()).add(protect)
    for feature in registry.findall("feature"):
        if "vulkan" not in feature.get("api", "").split(","):
            continue
        for requirement in feature.findall("require"):
            if requirement.get("api") and "vulkan" not in requirement.get("api").split(","):
                continue
            for t in requirement.findall("type"):
                if not t.get("api") or "vulkan" in t.get("api").split(","):
                    owners.setdefault(t.get("name"), set()).add(None)
    lines.append("static OwnedNode clone_input(const VkBaseOutStructure* node) {\n    switch (node->sType) {")
    for name, node in sorted(types.items()):
        if "VkDeviceCreateInfo" not in node.get("structextends", "").split(",") or node.get("alias"):
            continue
        if node.get("api") and "vulkan" not in node.get("api").split(","):
            continue
        guards = owners.get(name)
        if not guards:
            continue
        stype = node.find("member[@values]")
        if stype is None:
            continue
        if None not in guards:
            expressions = [f"defined({g})" for g in sorted(guards)]
            if "VK_USE_PLATFORM_ANDROID_KHR" in guards:
                expressions.append("defined(__ANDROID__)")
            lines.append("#if " + " || ".join(expressions))
        lines.append(f"    case {stype.get('values')}: return clone_node<{name}>(node);")
        if None not in guards:
            lines.append("#endif")
    lines.append("    default: return {};\n    }\n}")
    output = ROOT / "layer/src/main/cpp/core/promoted_feature_metadata.inc"
    output.write_text("\n".join(lines) + "\n", encoding="utf-8")

    # Immediate-call copies for timeline input rewrites. Ownership of pointer
    # payloads is deliberately separate from ownership of the pNext links.
    input_lines = ["// Generated by tools/generate_core_feature_metadata.py; do not edit.",
                   "static std::shared_ptr<VkBaseOutStructure> clone_input_node(const VkBaseInStructure* node, int kind, InputPNextCopy& owner, bool deep) {",
                   "    switch (node->sType) {"]
    for name, node in sorted(types.items()):
        parents = node.get("structextends", "").split(",")
        mask = sum(bit for parent, bit in (("VkSubmitInfo", 1), ("VkSemaphoreCreateInfo", 2),
                                           ("VkBindSparseInfo", 4)) if parent in parents)
        if not mask or node.get("alias") or name not in owners:
            continue
        if node.get("api") and "vulkan" not in node.get("api").split(","):
            continue
        guards = owners[name]
        if None not in guards:
            expressions = [f"defined({g})" for g in sorted(guards)]
            if "VK_USE_PLATFORM_ANDROID_KHR" in guards:
                expressions.append("defined(__ANDROID__)")
            input_lines.append("#if " + " || ".join(expressions))
        stype = node.find("member[@values]").get("values")
        input_lines.extend([f"    case {stype}: {{", f"        if (!(kind & {mask})) return {{}};",
                            f"        auto original = reinterpret_cast<const {name}*>(node);",
                            f"        auto owned = std::make_shared<{name}>(*original);", "        if (deep) {"])
        for member in node.findall("member"):
            field = member.findtext("name")
            if field == "pNext" or "*" not in "".join(member.itertext()):
                continue
            length = member.get("len", "")
            if length.isidentifier():
                element = types.get(member.findtext("type"))
                assert element is None or not element.find("member[name='pNext']"), (name, field)
                input_lines.append(f"            owned->{field} = owner.retain_array(original->{field}, original->{length});")
            else:
                input_lines.append(f"            if (original->{field}) return {{}}; // Unsupported pointer payload, never borrow asynchronously.")
        input_lines.extend(["        }", "        return {owned, reinterpret_cast<VkBaseOutStructure*>(owned.get())};", "    }"])
        if None not in guards:
            input_lines.append("#endif")
    input_lines.extend(["    default: return {};", "    }", "}"])
    (ROOT / "layer/src/main/cpp/core/input_pnext_metadata.inc").write_text(
        "\n".join(input_lines) + "\n", encoding="utf-8")

    inventory = {"registry": "Vulkan-Headers/registry/vk.xml", "versions": {}}
    for version in (11, 12):
        feature = registry.find(f"feature[@name='VK_VERSION_1_{version - 10}']")
        components = [f for f in registry.findall("feature")
                      if f.get("number") == f"1.{version - 10}"
                      and "vulkan" in f.get("api", "").split(",")]
        inventory["versions"][f"1.{version - 10}"] = {
            "commands": sorted({c.get("name") for f in components for c in f.findall("./require/command")
                                if not c.get("api") or "vulkan" in c.get("api").split(",")}),
            "aggregate_features": members(f"VkPhysicalDeviceVulkan{version}Features"),
            "aggregate_properties": [m.findtext("name") for m in
                                     types[f"VkPhysicalDeviceVulkan{version}Properties"].findall("member")
                                     if m.findtext("name") not in ("sType", "pNext")],
            "promoted_feature_structs": [name for v, name, _ in GROUPS if v == version],
            "feature_requirements": [f.attrib for f in feature.findall("./require/feature")],
            "promoted_extensions": sorted(e.get("name") for e in registry.findall("./extensions/extension")
                                          if e.get("promotedto") == f"VK_VERSION_1_{version - 10}"),
        }
    path = ROOT / "docs/vulkan_core_inventory.json"
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(json.dumps(inventory, indent=2) + "\n", encoding="utf-8")
    total = sum(len(members(f"VkPhysicalDeviceVulkan{v}Features")) for v in (11, 12))
    print(f"Generated {len(GROUPS)} groups and {total} aggregate feature mappings")


if __name__ == "__main__":
    generate()
