"""Generate byte-accurate Vulkan 1.1/1.2 property promotion maps."""
from pathlib import Path
import xml.etree.ElementTree as ET

ROOT = Path(__file__).resolve().parents[1]
GROUPS = [
    (11, "VkPhysicalDeviceIDProperties", "VK_KHR_external_memory_capabilities", True),
    (11, "VkPhysicalDeviceSubgroupProperties", "", False),
    (11, "VkPhysicalDevicePointClippingProperties", "VK_KHR_maintenance2", False),
    (11, "VkPhysicalDeviceMultiviewProperties", "VK_KHR_multiview", False),
    (11, "VkPhysicalDeviceProtectedMemoryProperties", "", False),
    (11, "VkPhysicalDeviceMaintenance3Properties", "VK_KHR_maintenance3", False),
    (12, "VkPhysicalDeviceDriverProperties", "VK_KHR_driver_properties", False),
    (12, "VkPhysicalDeviceFloatControlsProperties", "VK_KHR_shader_float_controls", False),
    (12, "VkPhysicalDeviceDescriptorIndexingProperties", "VK_EXT_descriptor_indexing", False),
    (12, "VkPhysicalDeviceDepthStencilResolveProperties", "VK_KHR_depth_stencil_resolve", False),
    (12, "VkPhysicalDeviceSamplerFilterMinmaxProperties", "VK_EXT_sampler_filter_minmax", False),
    (12, "VkPhysicalDeviceTimelineSemaphoreProperties", "VK_KHR_timeline_semaphore", False),
]
RENAMES = {"supportedStages": "subgroupSupportedStages",
           "supportedOperations": "subgroupSupportedOperations",
           "quadOperationsInAllStages": "subgroupQuadOperationsInAllStages"}


def generate():
    registry = ET.parse(ROOT / "Vulkan-Headers/registry/vk.xml").getroot()
    types = {t.get("name") or t.findtext("name"): t for t in registry.findall("./types/type")}
    fields = lambda name: [m.findtext("name") for m in types[name].findall("member")
                           if m.findtext("name") not in ("sType", "pNext")]
    covered = {11: set(), 12: {"framebufferIntegerColorSampleCounts"}}
    lines = ["// Generated by tools/generate_core_property_metadata.py; do not edit."]
    for i, (version, name, _, _) in enumerate(GROUPS):
        aggregate = f"VkPhysicalDeviceVulkan{version}Properties"
        lines.append(f"static const PropertyField fields_{i}[] = {{")
        for member in fields(name):
            target = RENAMES.get(member, member) if version == 11 else member
            covered[version].add(target)
            lines.append(f"    {{offsetof({aggregate}, {target}), offsetof({name}, {member}), "
                         f"sizeof((({name}*)nullptr)->{member})}},")
        lines.append("};")
    lines.append("static const PropertyGroup property_groups[] = {")
    for i, (version, name, extension, instance) in enumerate(GROUPS):
        stype = types[name].find("member[@values]").get("values")
        lines.append(f'    {{{version}, {stype}, "{extension}", {str(instance).lower()}, '
                     f'fields_{i}, std::size(fields_{i}), make_property<{name}>, reset_property<{name}>}},')
    lines.append("};")
    for version in (11, 12):
        assert covered[version] == set(fields(f"VkPhysicalDeviceVulkan{version}Properties")), version
    lines.append("static const VkFormat integer_color_formats[] = {")
    # Every integer color format in Vulkan 1.0. Depth/stencil and compressed
    # formats cannot be integer color attachments.
    enums = {e.get("name"): e.get("value") for e in registry.findall("./enums[@name='VkFormat']/enum")}
    for fmt in registry.findall("./formats/format"):
        value = enums.get(fmt.get("name"))
        components = fmt.findall("component")
        if (value and int(value, 0) < 185 and not fmt.get("compressed") and components
                and all(c.get("name") not in ("D", "S") for c in components)
                and all(c.get("numericFormat") in ("UINT", "SINT") for c in components)):
            lines.append(f"    {fmt.get('name')},")
    lines.append("};")
    (ROOT / "layer/src/main/cpp/core/promoted_property_metadata.inc").write_text(
        "\n".join(lines) + "\n", encoding="utf-8")
    # Black-box comparison: raw driver child queries versus the public layer's
    # aggregate output. This also detects module hooks overwriting real values.
    checks = ["// Generated raw-driver property comparisons; do not edit."]
    for version, name, extension, instance in GROUPS:
        stype = types[name].find("member[@values]").get("values")
        condition = f"native_api >= VK_API_VERSION_1_{version - 10}"
        if extension:
            condition += f' || {"instance_extensions" if instance else "extensions"}.count("{extension}")'
        checks.extend([f"if ({condition}) {{", f"    {name} native{{{stype}}};",
                       "    VkPhysicalDeviceProperties2 direct{VK_STRUCTURE_TYPE_PHYSICAL_DEVICE_PROPERTIES_2, &native};",
                       "    raw_query(physical, &direct);"])
        for member in fields(name):
            target = RENAMES.get(member, member) if version == 11 else member
            # Display strings identify the compatibility layer; the GPU runner
            # checks these separately, including aggregate/KHR agreement.
            if member in ("driverName", "driverInfo"):
                continue
            checks.append(f'    check(!memcmp(&actual{version}.{target}, &native.{member}, sizeof(native.{member})), "native property: {target}");')
        checks.append("}")
    (ROOT / "layer/src/main/cpp/tests/core_properties_checks.inc").write_text(
        "\n".join(checks) + "\n", encoding="utf-8")
    print(f"Generated {len(GROUPS)} property groups, {sum(map(len, covered.values()))} fields")


if __name__ == "__main__":
    generate()
