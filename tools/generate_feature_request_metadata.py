"""Generate typed feature-query fields for validating original device requests."""
import argparse
from pathlib import Path
import xml.etree.ElementTree as ET

ROOT = Path(__file__).resolve().parents[1]
OUTPUT = ROOT / 'layer/src/main/cpp/core/feature_request_metadata.inc'


def vulkan(element):
    return element.get('api') is None or 'vulkan' in element.get('api').split(',')


def generate():
    registry = ET.parse(ROOT / 'Vulkan-Headers/registry/vk.xml').getroot()
    platforms = {x.get('name'): x.get('protect') for x in registry.findall('./platforms/platform')}
    owners = {}
    for parent in list(registry.findall('feature')) + list(registry.findall('./extensions/extension')):
        extension = parent.tag == 'extension'
        if extension and 'vulkan' not in parent.get('supported', '').split(','):
            continue
        if not extension and not vulkan(parent):
            continue
        guard = platforms.get(parent.get('platform'))
        if parent.get('provisional') == 'true':
            guard = 'VK_ENABLE_BETA_EXTENSIONS'
        for requirement in parent.findall('require'):
            if vulkan(requirement):
                for ref in requirement.findall('type'):
                    if vulkan(ref):
                        owners.setdefault(ref.get('name'), set()).add(guard)
    structures = []
    lines = ['// Generated by tools/generate_feature_request_metadata.py; do not edit.']
    base = registry.find("./types/type[@name='VkPhysicalDeviceFeatures']")
    lines.append('static constexpr size_t base_fields[] = {')
    lines += [f'    offsetof(VkPhysicalDeviceFeatures, {m.findtext("name")}),'
              for m in base.findall('member') if vulkan(m)]
    lines.append('};')
    for node in registry.findall('./types/type'):
        name = node.get('name')
        if node.get('alias') or not vulkan(node) or 'VkPhysicalDeviceFeatures2' not in node.get('structextends', '').split(','):
            continue
        guards = owners.get(name)
        if not guards:
            continue
        fields = [m for m in node.findall('member') if vulkan(m) and m.findtext('name') not in ('sType', 'pNext')]
        assert fields and all(m.findtext('type') == 'VkBool32' for m in fields), name
        guard = None if None in guards else ' || '.join(f'defined({g})' for g in sorted(guards))
        if guard:
            lines.append(f'#if {guard}')
        lines.append(f'static constexpr size_t fields_{name}[] = {{')
        lines += ['    offsetof(%s, %s),' % (name, m.findtext('name')) for m in fields]
        lines.append('};')
        if guard:
            lines.append('#endif')
        stype = node.find("member[@values]").get('values')
        structures.append((name, stype, guard))
    lines.append('static const FeatureDescriptor feature_descriptors[] = {')
    for name, stype, guard in structures:
        if guard:
            lines.append(f'#if {guard}')
        lines.append(f'    {{{stype}, fields_{name}, std::size(fields_{name}), make_feature<{name}, {stype}>}},')
        if guard:
            lines.append('#endif')
    lines.append('};')
    return '\n'.join(lines) + '\n', len(structures)


if __name__ == '__main__':
    parser = argparse.ArgumentParser()
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    text, count = generate()
    if args.check:
        if not OUTPUT.exists() or OUTPUT.read_text(encoding='utf-8') != text:
            raise SystemExit('feature_request_metadata.inc is stale')
    else:
        OUTPUT.write_text(text, encoding='utf-8', newline='\n')
    print(f'{count} typed feature structures {"verified" if args.check else "generated"}')
